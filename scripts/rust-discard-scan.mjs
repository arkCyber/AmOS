#!/usr/bin/env node
/**
 * rust-discard-scan.mjs — type-aware scan for results that are silently thrown away.
 *
 * Why: R77 asked "is anything blocking an async worker?" and R80 asked "is a `std` lock
 * held across an `.await`?" — both times a **syntactic** scan was the only option, and both
 * reports said so: "a guard moved into another function, returned out of scope, or a
 * `parking_lot` lock whose `use` line does not name the type are all outside it (a type
 * checker would be needed)". This gate uses the type checker instead of guessing: it reads
 * `cargo clippy` diagnostics (JSON) for three lints that the compiler can only decide with
 * types in hand:
 *
 *   • `clippy::let_underscore_must_use` — `let _ = expr` where `expr` is `#[must_use]`.
 *     That is the explicit way to discard a `Result`, a `JoinHandle`, a `Guard`, or any
 *     other value the author of the API asked you to look at. This repository has 140 of
 *     them in production code and, until now, **no gate at all** on either side of the
 *     Rust/TS split (the frontend has `write-scan`; the Rust side had nothing). Of those,
 *     **82 are hand-written** (the gated, auditable surface) and **58 are generated by
 *     `#[tauri::command]`** — see the split below.
 *   • `clippy::await_holding_lock` / `await_holding_refcell_ref` — the *type-aware* version
 *     of R80's question. They are currently **0**, which independently confirms R80's
 *     conclusion (its scan was scope-aware, but still syntactic).
 *
 * Hand-written vs macro-generated (round 85). The very first version of this gate counted
 * all findings as "sites of debt to audit one by one", and that is what the baseline said.
 * It was wrong about a third of them: **`#[tauri::command]` expands to a wrapper that
 * discards a must-use value, and rustc reports it against `Span::call_site()` — the
 * function signature** — so `crates/amos-tauri/src/appstore.rs` looked like it had nine
 * discarded results when it has none (one per command, all generated), and a file with real
 * debt could look smaller than one without. The JSON cannot tell them apart (`expansion` is
 * `null` on those spans); the *source line* can, so the scan reads it: a line containing
 * `let _` is hand-written, a signature line is not. Only the hand-written set is ratcheted
 * (a macro-generated finding is not actionable at that line, and every new command adds
 * exactly one — gating it would be pure noise), and the macro count is printed so a
 * structural change is still visible.
 *
 * Measured and deliberately **not** gated: `.ok()` (189 production sites). Round 84 read a
 * sample of them: the overwhelming majority is the idiomatic "missing env var / unparsable
 * number ⇒ default" pattern (`std::env::var(X).ok()`, `parse::<usize>().ok()`), where the
 * absence of a value *is* the expected case. A gate over that would be pure noise, and a
 * regex cannot tell it apart from the interesting cases (a file that exists but cannot be
 * read silently becoming "empty"). Those were handled at the sites where they change what
 * the daemon reports — see `load_passages` in `rag_service.rs`, which now separates
 * "missing" from "corrupt" (REQ-A148).
 *
 * Ratchet, like `unsafe-scan` (this is debt, not a defect for every site): the per-file
 * counts of **hand-written** discards live in `scripts/rust-discard-baseline.json`
 * (`macroGenerated` there records the informational set). A file that gains a discard — or
 * a new file that appears with one — **fails** the gate until the addition is acknowledged
 * there; a file that drops below its baseline is reported `[stale]` so the baseline cannot
 * rot; a file that disappears is reported too.
 *
 * Run:
 *   node scripts/rust-discard-scan.mjs              # gate (runs clippy itself)
 *   node scripts/rust-discard-scan.mjs --json       # counts per file, for the baseline
 *   node scripts/rust-discard-scan.mjs --selftest   # pin the parser + classifier + ratchet
 */
import { readFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const BASELINE = join(root, "scripts", "rust-discard-baseline.json");

/** Lint codes this gate treats as findings (everything else clippy says is none of its business). */
export const WATCHED = [
  "clippy::let_underscore_must_use",
  "clippy::await_holding_lock",
  "clippy::await_holding_refcell_ref",
];

/**
 * Where a diagnostic's primary span points, as far as the *source* is concerned.
 *
 * `clippy::let_underscore_must_use` cannot tell a hand-written discard from the one a
 * proc-macro generates: `#[tauri::command]` expands to a wrapper that discards a
 * value, and rustc reports it against `Span::call_site()` — the **function signature**
 * (`expansion` is `null` there, so the JSON cannot be used to separate them). Reading
 * the reported line is what does separate them: a hand-written discard has `let _` on
 * it, a macro-generated finding points at `pub async fn … -> Result<…> {`.
 *
 * Why it matters: the ratchet's whole point is "debt a human can act on". Counting the
 * wrappers as sites made the file ordering meaningless (a file with 9 commands and no
 * hand-written discard looked like the second-worst offender) and told a reader that
 * 152 human sites were unaudited. Round 85 measured the split: 94 hand-written (gated)
 * vs 58 macro-generated (reported, not gated — one per command, nothing to fix).
 */
export const HAND_WRITTEN = /\blet\s+_(\s*=|;)/;

/** `true` when `line` is a source line a human wrote a discard on. */
export function isHandWritten(line) {
  return HAND_WRITTEN.test(line ?? "");
}

/**
 * Fold `cargo clippy --message-format=json` output into `{ "file": n }` counts plus the findings.
 * Only diagnostics whose code is in [`WATCHED`] are counted; a diagnostic with no span (a
 * crate-level message) is counted under its lint name so it
 * cannot vanish.
 */
export function findingsFromMessages(text, readLine = defaultReadLine) {
  const perFile = new Map();
  const perFileMacro = new Map();
  const perLint = new Map();
  const findings = [];
  for (const line of text.split("\n")) {
    if (line.trim() === "" || !line.startsWith("{")) continue;
    let msg;
    try {
      msg = JSON.parse(line);
    } catch {
      continue; // not a JSON diagnostic (cargo progress goes to stderr anyway)
    }
    if (msg.reason !== "compiler-message") continue;
    const message = msg.message;
    const code = message?.code?.code;
    if (!code || !WATCHED.includes(code)) continue;
    const span = (message.spans ?? []).find((s) => s.is_primary) ?? message.spans?.[0];
    const file = span?.file_name ?? `<no span: ${code}>`;
    const lineNo = span?.line_start ?? 0;
    // Only the must-use lint can be macro-generated noise; an `await_holding_*` finding is
    // about a guard binding, i.e. always something a human wrote and can act on.
    const written =
      code !== "clippy::let_underscore_must_use" || isHandWritten(readLine(file, lineNo));
    // The ratchet counts the sites a human can act on; a macro-generated finding (the
    // `#[tauri::command]` wrapper, attributed to the signature) is reported separately.
    if (written) perFile.set(file, (perFile.get(file) ?? 0) + 1);
    else perFileMacro.set(file, (perFileMacro.get(file) ?? 0) + 1);
    perLint.set(code, (perLint.get(code) ?? 0) + 1);
    findings.push({
      file,
      line: lineNo,
      code,
      // `hand` = a source line with `let _` on it; `macro` = a generated span (see
      // `HAND_WRITTEN`). Readers of `--json` get the classification, not just counts.
      origin: written ? "hand" : "macro",
      message: (message.message ?? "").split("\n")[0],
    });
  }
  const sort = (m) => Object.fromEntries([...m].sort(([a], [b]) => (a < b ? -1 : 1)));
  return {
    perFile: sort(perFile),
    perFileMacro: sort(perFileMacro),
    perLint: sort(perLint),
    findings,
  };
}

/**
 * Read one source line for the classifier. Cached per file (a scan reads a handful of
 * lines per file at most, but the diagnostic stream is long); a file that cannot be read
 * yields `""`, which classifies as `macro` — a missing file must never *inflate* the
 * gated count.
 */
const lineCache = new Map();
function defaultReadLine(file, line) {
  if (file.startsWith("<")) return "";
  let lines = lineCache.get(file);
  if (lines === undefined) {
    try {
      lines = readFileSync(join(root, file), "utf8").split("\n");
    } catch {
      lines = null;
    }
    lineCache.set(file, lines);
  }
  if (!lines || line < 1 || line > lines.length) return "";
  return lines[line - 1];
}

/**
 * Compare counts against the baseline. Returns the problems (failures) and the stale
 * entries (informational — the baseline should be tightened).
 */
export function ratchet(counts, baseline) {
  const problems = [];
  const stale = [];
  for (const [file, n] of Object.entries(counts)) {
    const b = baseline[file];
    if (b === undefined) {
      problems.push(
        `new discarded result: ${file} (${n}) — acknowledge it in scripts/rust-discard-baseline.json, or handle the value`,
      );
    } else if (n > b) {
      problems.push(`more discards than baselined: ${file} (${n} > ${b})`);
    } else if (n < b) {
      stale.push(`${file} (baseline ${b}, now ${n})`);
    }
  }
  for (const file of Object.keys(baseline)) {
    if (!(file in counts)) stale.push(`${file} (baseline ${baseline[file]}, now 0)`);
  }
  return { problems, stale: stale.sort() };
}

// --- main --------------------------------------------------------------------
const args = process.argv.slice(2);

/**
 * Run clippy over the workspace's production targets (`--lib --bins`: `#[cfg(test)]` code
 * and test/example targets are excluded, since discarding a temp-file cleanup result there
 * is idiomatic and not what this gate is about). The lints are requested as *warnings* so
 * the run always completes and this gate — not clippy's exit code — decides.
 *
 * **Two passes** (REQ-A187): the second enables every `android` feature this workspace
 * has. Without it the whole device-facing surface is invisible to a clippy-based gate —
 * `#[cfg(feature = "android")]` code is not compiled, so nothing is reported. Measured
 * when this was added: **113 discard sites existed only in the featured pass**, nine of
 * them real silent failures (a dropped camera frame, a failed glue-bus arm, an undelivered
 * in-call/SMS event, an unbound dial/sensor context, an unwritten self-check report, a
 * dropped mic-permission reply).
 */
const ANDROID_FEATURES = [
  "amos-tauri/android",
  "amos-radio/android",
  "amos-sensor/android",
  "amos-media/android",
  "amos-power/android",
  "amos-profiling/android",
  "amos-flashlight/android",
  "amos-sms/android",
  "amos-telephony/android",
  "amos-clipboard/android",
];

function clippyPass(extra) {
  try {
    return execFileSync(
      "cargo",
      [
        "clippy",
        "--workspace",
        "--lib",
        "--bins",
        "--message-format=json",
        ...extra,
        "--",
        ...WATCHED.flatMap((lint) => ["-W", lint]),
      ],
      { cwd: root, encoding: "utf8", maxBuffer: 256 * 1024 * 1024, stdio: ["ignore", "pipe", "pipe"] },
    );
  } catch (e) {
    // A build failure still produces diagnostics on stdout; only a run that produced
    // *nothing* is a hard error (otherwise a red build would look like "0 findings").
    if (typeof e.stdout === "string" && e.stdout.includes('"reason":"compiler-message"')) {
      return e.stdout;
    }
    throw e;
  }
}

/**
 * Keep the first occurrence of each diagnostic, keyed by lint + primary span: the two
 * passes above report the *same* warning for every file whose diagnostics do not depend
 * on the feature (otherwise each non-Android discard would be counted twice and the
 * ratchet would read as "everything doubled").
 */
export function dedupeMessages(text) {
  const seen = new Set();
  const out = [];
  for (const line of text.split("\n")) {
    if (line.trim() === "" || !line.startsWith("{")) {
      continue;
    }
    let msg;
    try {
      msg = JSON.parse(line);
    } catch {
      continue;
    }
    if (msg.reason !== "compiler-message") {
      continue;
    }
    const code = msg.message?.code?.code ?? "";
    const span = (msg.message?.spans ?? []).find((s) => s.is_primary);
    const key = `${code}::${span?.file_name ?? ""}::${span?.line_start ?? 0}::${span?.column_start ?? 0}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(line);
  }
  return out.join("\n");
}

function runClippy() {
  const plain = clippyPass([]);
  const featured = clippyPass(["--features", ANDROID_FEATURES.join(",")]);
  return dedupeMessages(`${plain}\n${featured}`);
}

function runSelfTest() {
  let failures = 0;
  let assertions = 0;
  const check = (name, ok) => {
    assertions += 1;
    if (!ok) {
      failures += 1;
      console.error(`[rust-discard-scan] selftest FAIL: ${name}`);
    }
  };
  const diag = (code, file, line) =>
    JSON.stringify({
      reason: "compiler-message",
      message: {
        message: "non-binding `let` on an expression with `#[must_use]` type",
        level: "warning",
        code: { code },
        spans: [{ file_name: file, line_start: line, is_primary: true }],
      },
    });

  const sample = [
    '{"reason":"compiler-artifact","package_id":"x"}',
    diag("clippy::let_underscore_must_use", "crates/a/src/lib.rs", 10),
    diag("clippy::let_underscore_must_use", "crates/a/src/lib.rs", 20),
    diag("clippy::await_holding_lock", "crates/a/src/lib.rs", 30),
    diag("clippy::await_holding_refcell_ref", "crates/b/src/lib.rs", 5),
    diag("clippy::unwrap_used", "crates/a/src/lib.rs", 99),
    "not json at all",
    "",
  ].join("\n");
  // The classifier reads the *reported* line: that is what separates a hand-written
  // discard from a `#[tauri::command]` wrapper (which clippy attributes to the
  // signature, with `expansion: null`, so the JSON cannot tell them apart).
  const fakeSource = {
    "crates/a/src/lib.rs": {
      10: "    let _ = session.stop();",
      20: "pub async fn list(state: State<'_, Bridge>) -> Result<Vec<String>, String> {",
      30: "    let guard = lock.lock();",
    },
    "crates/b/src/lib.rs": { 5: "  }" },
  };
  const readLine = (file, line) => fakeSource[file]?.[line] ?? "";
  const got = findingsFromMessages(sample, readLine);
  check("counts per file", JSON.stringify(got.perFile) === '{"crates/a/src/lib.rs":2,"crates/b/src/lib.rs":1}');
  check("counts per lint", got.perLint["clippy::let_underscore_must_use"] === 2);
  check("unwatched lint is ignored", !got.findings.some((f) => f.code === "clippy::unwrap_used"));
  check("line numbers are captured", got.findings[0].line === 10);
  check("non-JSON lines do not throw", got.findings.length === 4);
  // `dedupeMessages` (REQ-A187): the gate runs clippy twice (plain + android features) and
  // the same warning appears in both outputs — counting it twice would make the ratchet
  // read as "everything doubled" (which is exactly what happened on the first attempt).
  const deduped = dedupeMessages([sample, sample].join("\n"));
  check(
    "duplicate diagnostics from the two passes collapse",
    findingsFromMessages(deduped, readLine).findings.length === got.findings.length,
  );
  check(
    "a same-file different-lint diagnostic is kept",
    findingsFromMessages(dedupeMessages(diag("clippy::await_holding_lock", "crates/a/src/lib.rs", 30)), readLine).findings.length === 1,
  );


  // Classification: the ratchet counts hand-written discards only.
  const gotSplit = findingsFromMessages(sample, readLine);
  check(
    "a line with `let _` counts as hand-written",
    gotSplit.perFile["crates/a/src/lib.rs"] === 2,
  );
  check(
    "a signature-attributed finding is not hand-written",
    gotSplit.perFileMacro["crates/a/src/lib.rs"] === 1,
  );
  check(
    "the two buckets add up to every finding",
    Object.values(gotSplit.perFile).reduce((a, b) => a + b, 0) +
      Object.values(gotSplit.perFileMacro).reduce((a, b) => a + b, 0) ===
      gotSplit.findings.length,
  );
  check(
    "findings carry their origin",
    gotSplit.findings.find((f) => f.line === 20)?.origin === "macro" &&
      gotSplit.findings.find((f) => f.line === 10)?.origin === "hand",
  );
  check(
    "an unreadable file cannot inflate the gated count",
    // The two `await_holding_*` findings stay (they are never macro-generated); both
    // must-use findings fall into the informational bucket.
    JSON.stringify(findingsFromMessages(sample, () => "").perFile) ===
      '{"crates/a/src/lib.rs":1,"crates/b/src/lib.rs":1}',
  );
  check("`let _ =` is hand-written", isHandWritten("    let _ = drop(guard);"));
  check("`let _;` is hand-written", isHandWritten("let _;"));
  check("`let _guard = …` is not a discard", !isHandWritten("let _guard = lock.lock();"));
  check("a bare signature line is not a discard", !isHandWritten(") -> Result<(), String> {"));
  check("a line without `let` is not a discard", !isHandWritten("    self.persist();"));

  const base = { "crates/a/src/lib.rs": 3 };
  check(
    "equal counts pass",
    ratchet({ "crates/a/src/lib.rs": 3 }, base).problems.length === 0,
  );
  check(
    "an increase fails",
    ratchet({ "crates/a/src/lib.rs": 4 }, base).problems[0].includes("4 > 3"),
  );
  check(
    "a new file fails",
    ratchet({ "crates/b/src/lib.rs": 1 }, base).problems[0].includes("new discarded result"),
  );
  check(
    "a decrease is stale, not a failure",
    ratchet({ "crates/a/src/lib.rs": 2 }, base).stale[0].includes("baseline 3"),
  );
  check(
    "a vanished file is stale",
    ratchet({}, base).stale[0].includes("now 0"),
  );
  check("no baseline ⇒ everything new is a problem", ratchet({ "x.rs": 1 }, {}).problems.length === 1);

  console.log(`[rust-discard-scan] selftest: ${assertions} assertion(s), ${failures} failure(s).`);
  process.exit(failures === 0 ? 0 : 1);
}

function main() {
  const text = runClippy();
  const { perFile, perFileMacro, perLint, findings } = findingsFromMessages(text);
  if (args.includes("--json")) {
    console.log(JSON.stringify({ perFile, perFileMacro, perLint, findings }, null, 2));
  }
  const baseline = existsSync(BASELINE)
    ? (JSON.parse(readFileSync(BASELINE, "utf8")).files ?? {})
    : {};
  const { problems, stale } = ratchet(perFile, baseline);
  const total = Object.values(perFile).reduce((a, b) => a + b, 0);
  const macro = Object.values(perFileMacro).reduce((a, b) => a + b, 0);

  if (stale.length > 0) {
    console.log("[rust-discard-scan] note — baseline entries to tighten:");
    for (const s of stale) console.log(`  [stale] ${s}`);
  }
  if (problems.length > 0) {
    for (const p of problems) console.error(`[rust-discard-scan] ${p}`);
    console.error(
      `[rust-discard-scan] FAIL — ${problems.length} problem(s); ${total} hand-written discard(s) in production code (baseline total ${Object.values(baseline).reduce((a, b) => a + b, 0)}).`,
    );
    return 1;
  }
  console.log(
    `[rust-discard-scan] ${total} hand-written discarded must-use value(s) in production code, none above the baseline; ` +
      `${macro} attributed to macro-generated spans (Tauri command wrappers — informational, nothing to fix there); ` +
      `await-holding-lock/refcell: ${perLint["clippy::await_holding_lock"] ?? 0}/${perLint["clippy::await_holding_refcell_ref"] ?? 0} (type-checked). OK.`,
  );
  return 0;
}

if (args.includes("--selftest")) {
  runSelfTest();
} else {
  process.exit(main());
}
