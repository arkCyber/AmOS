#!/usr/bin/env node
/**
 * rust-macro-scan.mjs — Power of 10 rule #10's missing gate: the **macro whitelist**.
 *
 * `docs/POWER_OF_10.md` rule #10 claimed 「无 `macro_rules!` 自定义宏（搜索：`grep macro_rules crates/`
 * 0 处生产代码）」. Read back on 2026-09-19 that claim is **false**: `grep -rn 'macro_rules!' crates/*​/src`
 * finds **four** production definitions —
 *
 *   `amos-jni::jni_call` … `amos-link::zenoh::{forward_samples, forward_latest}` … `amos-radio::android::jni`
 *
 * — each deliberate and each already documented at its definition (the JNI two exist because the wrappers
 * take `&mut self`: the borrow has to end before the shared-borrow exception check, which a function
 * cannot express; the Zenoh two because the handler types share no trait for `recv_async`). The audit was
 * not wrong about the *code*; it was wrong about the *measurement*, and an aerospace audit may not assert
 * what it never measured. So the property is now **enforced** instead of claimed: every production
 * `macro_rules!` must be registered with a reason, in both directions (a new macro fails; an exemption
 * whose macro is gone fails too, so the ratchet cannot rot).
 *
 * Rules (all fail):
 *   R1 `unlisted-macro`  — a `macro_rules!` definition in production Rust (`crates/<crate>/src/**`) that
 *                          is not in `scripts/rust-macro-allowlist.json`;
 *   R2 `stale-exemption` — an allowlist entry whose macro no longer exists;
 *   R3 `missing-reason`  — an entry without a real `why`;
 *   R4 `duplicate-entry` — the same `(crate, name)` listed twice.
 *
 * Boundaries (measured, not assumed — the rule every scanner here follows):
 *   • `crates/<crate>/tests/**` is **not** production: `amos-link/tests/robot_cases.rs` defines the
 *     `eventually!` fixture, and test code is out of scope by design;
 *   • a definition inside a `#[cfg(test)]` module inside `src/` **would** be counted (there are none
 *     today). The documented fix is an allowlist entry with `why: "test fixture"` — not a cleverer regex
 *     that a future reader has to re-derive;
 *   • the match is line-anchored (`^[ \t]*macro_rules![ \t]*<name>`) on purpose: a doc comment that
 *     merely *mentions* the token begins with `///` (or `//!`, or `*`) and cannot match, so — unlike the
 *     recursion scan, which analyses arbitrary call expressions — no comment/string masking is needed to
 *     analyse a *declaration form*. A `macro_rules!` generated by another macro is indented and is caught
 *     by the same line rule.
 */
import { readdirSync, readFileSync, statSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const cratesDir = join(repoRoot, "crates");
const allowlistPath = join(repoRoot, "scripts", "rust-macro-allowlist.json");

const SKIP_DIRS = new Set(["node_modules", "target", ".git", "gen", "tests"]);

/** Every production `.rs` file under `crates/<crate>/src/**`. */
function productionFiles() {
  const out = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (SKIP_DIRS.has(entry.name)) continue;
        walk(join(dir, entry.name));
      } else if (entry.name.endsWith(".rs")) {
        out.push(join(dir, entry.name));
      }
    }
  };
  for (const crate of readdirSync(cratesDir, { withFileTypes: true })) {
    if (!crate.isDirectory()) continue;
    const src = join(cratesDir, crate.name, "src");
    if (existsSync(src) && statSync(src).isDirectory()) walk(src);
  }
  return out.sort();
}

/** The crate a production file belongs to (`crates/<crate>/src/...`). */
export function crateOf(file) {
  return relative(cratesDir, file).split(/[\\/]/)[0];
}

/** `macro_rules!` definitions in one source: `{ name, line }`, in file order. */
export function definitionsIn(src) {
  const out = [];
  src.split("\n").forEach((text, i) => {
    const m = /^[ \t]*macro_rules![ \t]*([A-Za-z_][A-Za-z0-9_]*)/.exec(text);
    if (m) out.push({ name: m[1], line: i + 1 });
  });
  return out;
}

/** Problems in one crate's sources against one allowlist, as `{ rule, detail }`. */
export function problemsIn(files, allowlist) {
  const problems = [];
  const seen = new Map();
  for (const [file, src] of files) {
    for (const def of definitionsIn(src)) {
      const key = `${crateOf(file)}::${def.name}`;
      const hits = seen.get(key) ?? [];
      hits.push({ file, line: def.line });
      seen.set(key, hits);
    }
  }
  for (const [key, hits] of seen) {
    const [crate, name] = key.split("::");
    if (allowlist.some((e) => e.crate === crate && e.name === name)) continue;
    for (const h of hits) {
      problems.push({
        rule: "unlisted-macro",
        detail: `${relative(repoRoot, h.file)}:${h.line} — macro_rules! ${name} (crate ${crate}) is not in scripts/rust-macro-allowlist.json`,
      });
    }
  }
  for (const entry of allowlist) {
    if (!entry.why || entry.why.trim().length < 12) {
      problems.push({
        rule: "missing-reason",
        detail: `${entry.crate}::${entry.name} has no real \`why\` (a placeholder is not a reason)`,
      });
    }
    if (!seen.has(`${entry.crate}::${entry.name}`)) {
      problems.push({
        rule: "stale-exemption",
        detail: `${entry.crate}::${entry.name} is listed but no longer defined (remove the entry)`,
      });
    }
  }
  const keys = allowlist.map((e) => `${e.crate}::${e.name}`);
  for (const dup of new Set(keys.filter((k, i) => keys.indexOf(k) !== i))) {
    problems.push({ rule: "duplicate-entry", detail: `${dup} is listed twice` });
  }
  return { problems, found: [...seen.keys()].sort() };
}

function loadAllowlist() {
  if (!existsSync(allowlistPath)) {
    console.error(`[rust-macro-scan] FAIL — ${relative(repoRoot, allowlistPath)} is missing`);
    process.exit(1);
  }
  const entries = JSON.parse(readFileSync(allowlistPath, "utf8")).entries ?? [];
  if (!Array.isArray(entries)) {
    console.error("[rust-macro-scan] FAIL — the allowlist's `entries` must be an array");
    process.exit(1);
  }
  return entries;
}

function main() {
  const allowlist = loadAllowlist();
  const files = productionFiles().map((f) => [f, readFileSync(f, "utf8")]);
  const { problems, found } = problemsIn(files, allowlist);
  if (problems.length > 0) {
    console.error(`[rust-macro-scan] FAIL — ${problems.length} problem(s) with production macros:`);
    for (const p of problems) console.error(`  ${p.rule}: ${p.detail}`);
    console.error(
      "\nFix by spending the macro (prefer a function / trait / generic), or — if it really cannot be\n" +
        "one — add it to scripts/rust-macro-allowlist.json with a `why` naming the borrow/generic/API\n" +
        "constraint that forces a macro. There is deliberately no `--update` writer: an exemption is a\n" +
        "decision a human writes down (Power of 10 rule #10).",
    );
    process.exit(1);
  }
  console.log(
    `[rust-macro-scan] OK — ${found.length} production macro(s), all registered with a reason:\n` +
      found.map((k) => `  • ${k}`).join("\n"),
  );
}

/** The shapes the rules must catch, and the shapes they must not (negative controls). */
function selftest() {
  const checks = [];
  const check = (name, ok) => checks.push({ name, ok });
  const crate = join(cratesDir, "amos-jni", "src", "lib.rs");
  const entry = (name, why = "a real reason, long enough to pass the length floor") => ({
    crate: "amos-jni",
    name,
    why,
  });
  const listed = [[crate, "#[macro_export]\nmacro_rules! jni_call {\n    () => {};\n}\n"]];

  check("a registered macro passes", problemsIn(listed, [entry("jni_call")]).problems.length === 0);
  // (R1) the shape the tree actually had: a production macro nobody registered.
  check(
    "R1 catches an unregistered macro",
    problemsIn(listed, []).problems.some((p) => p.rule === "unlisted-macro"),
  );
  // (R2) the ratchet's other direction: an exemption whose macro is gone.
  check(
    "R2 catches a stale exemption",
    problemsIn(listed, [entry("jni_call"), entry("gone")]).problems.some(
      (p) => p.rule === "stale-exemption",
    ),
  );
  // (R3) no reasonless exemptions.
  check(
    "R3 catches a placeholder reason",
    problemsIn(listed, [entry("jni_call", "TODO")]).problems.some(
      (p) => p.rule === "missing-reason",
    ),
  );
  // (R4) one entry per macro.
  check(
    "R4 catches a duplicate entry",
    problemsIn(listed, [entry("jni_call"), entry("jni_call")]).problems.some(
      (p) => p.rule === "duplicate-entry",
    ),
  );
  // A doc comment *mentioning* the token is not a definition (the boundary stated in the header).
  check(
    "a doc comment that mentions macro_rules! is not a definition",
    problemsIn(
      [[crate, "/// Use `macro_rules! foo` to…\n//  macro_rules! bar {}\nfn x() {}\n"]],
      [],
    ).problems.length === 0,
  );
  // Indentation is tolerated, so a macro emitted by another macro is still seen (documented).
  check(
    "an indented definition is still counted",
    problemsIn([[crate, "    macro_rules! nested {\n        () => {};\n    }\n"]], []).problems.some(
      (p) => p.rule === "unlisted-macro",
    ),
  );
  // Test files are not production (the tree depends on it: `eventually!` lives in one).
  check(
    "crates/<crate>/tests/** is not scanned",
    productionFiles().every((f) => !relative(repoRoot, f).includes("/tests/")),
  );

  const failed = checks.filter((c) => !c.ok);
  for (const c of checks) console.log(`  ${c.ok ? "ok  " : "FAIL"} ${c.name}`);
  console.log(
    `[rust-macro-scan] selftest: ${checks.length} assertion(s), ${failed.length} failure(s).`,
  );
  if (failed.length > 0) process.exit(1);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  // An unrecognised flag is a failure, not a no-op (see `rust-recursion-scan.mjs` for the
  // measurement: a docs block spelled the selftest `--self-test`, which no `-scan` gate
  // implements, so the "verification" line silently ran the gate instead).
  const KNOWN_FLAGS = new Set(["--selftest"]);
  const unknown = process.argv.slice(2).filter((f) => f.startsWith("-") && !KNOWN_FLAGS.has(f));
  if (unknown.length > 0) {
    console.error(
      `[rust-macro-scan] unknown flag(s): ${unknown.join(", ")} — known: ${[...KNOWN_FLAGS].join(", ")}`,
    );
    process.exit(2);
  }
  if (process.argv.includes("--selftest")) selftest();
  else main();
}
