#!/usr/bin/env node
/**
 * ime-action-scan.mjs — "the input method advertises the action the platform actually queries for".
 *
 * The defect (REQ-A1897 / F-DEV-163). `AndroidManifest.components.xml` declared
 *
 *     <action android:name="android.view.inputmethod.InputMethod" />
 *
 * — the **package-shaped** spelling of `InputMethod.SERVICE_INTERFACE`, which reads as the
 * obvious one (it is the class name, lowercased like every other intent action in this
 * repository) and matches nothing. The platform discovers IMEs with
 * `new Intent(InputMethod.SERVICE_INTERFACE)` in Android 14's
 * `InputMethodManagerService.buildInputMethodListLocked` → `queryInputMethodServicesInternal`,
 * and that constant is the **camelCase** `android.view.InputMethod`.
 *
 * Nothing here could see it, and that is the point of this file. The service installs; the
 * package manager resolves it (`dumpsys package com.amos.ai` prints the action, the
 * `BIND_INPUT_METHOD` permission and the `@xml/method` meta-data, all correct); and
 * `adb shell ime list -a` still shows only the two Google IMEs, because IMMS drops a service
 * the query never returned **silently** — `filterInputMethodServices` logs for a missing
 * permission and for a malformed subtype, but has no arm at all for "the intent filter did not
 * match". `ime enable` then answers `Unknown input method ... cannot be enabled for user #0`.
 *
 * It was found by installing a known-good third-party IME (F-Droid's SimpleKeyboard) and
 * diffing its intent filter against ours — the device, not a test, held the answer. Two host
 * gates had already looked at this very block and passed:
 * `android-component-scan.mjs` (K4) because **its own table had been taught the wrong action**,
 * and `android-glue-mirror.sh` because it compares fragment↔generated by `android:name`, and
 * both copies carried the same wrong literal.
 *
 * The authority is **not** in this repository — it is the platform class the APK is built
 * against. It was read off the artifact, not remembered:
 *
 *   javap -constants -classpath $ANDROID_HOME/platforms/android-36/android.jar \
 *         android.view.inputmethod.InputMethod
 *   public static final java.lang.String SERVICE_INTERFACE = "android.view.InputMethod";
 *
 * `SERVICE_INTERFACE` below is that value, and R3 re-reads it off `android.jar` whenever
 * `javap` and an SDK are resolvable, so a pin that drifts from the platform goes red on any
 * machine that can check it rather than silently blessing the same wrong string twice.
 *
 * The same trap has a **second constant** one line below: `<meta-data android:name="android.view.im">`
 * is `SERVICE_META_DATA`, and it is what points the platform at `res/xml/method.xml` (the subtype
 * list). Spelled by analogy (`android.view.inputmethod.…`) it is equally silent — the IME appears
 * in the keyboard list with no languages. R4 pins it too.
 *
 * The third place the same literal lives is **this repository's own gate**: `android-component-scan.mjs`
 * judges every manifest action against its closed `PLATFORM_ACTIONS` table, so a table taught the
 * wrong spelling passes the wrong manifest *and* reddens the next round that spells it right. That
 * is exactly how the defect shipped — R5 pins the table's key to the platform constant.
 *
 * Rules:
 *   R0 floors    — the fragment's IME service and its action were both found (a file we could
 *                  not read is red, not vacuously green), and the pinned constants are non-empty.
 *   R1 fragment  — the tracked fragment's `AmosImeService` action is the platform constant.
 *   R2 generated — when the generated manifest is on disk (git-ignored; it is the file actually
 *                  compiled), its action is the constant too, so the documented hand-merge
 *                  cannot drift. Absent, R2 prints that it did not run — a skip that says so,
 *                  not one that looks like a pass.
 *   R3 authority — `javap -constants` against the SDK's `android.jar` equals the pins. Skipped,
 *                  with a line, on a machine without either.
 *   R4 meta-data — the same `<service>`'s `<meta-data android:name>` is `SERVICE_META_DATA`.
 *   R5 table     — `android-component-scan.mjs`'s `PLATFORM_ACTIONS` keys the IME on that same
 *                  action, so the gate cannot authenticate its own spelling.
 *
 * Usage (repo root):
 *   node scripts/ime-action-scan.mjs              # gate
 *   node scripts/ime-action-scan.mjs --selftest   # pin the parsers with fixtures
 *   node scripts/ime-action-scan.mjs --json
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FRAGMENT = "crates/amos-tauri/android-glue/AndroidManifest.components.xml";
const GENERATED = "crates/amos-tauri/gen/android/app/src/main/AndroidManifest.xml";
/** The gate whose own table judges every manifest action — R5 keeps it honest. */
const SCAN = "scripts/android-component-scan.mjs";
const IME_SERVICE = "AmosImeService";
const PLATFORM_CLASS = "android.view.inputmethod.InputMethod";

/** Verbatim from the `javap -constants` dump quoted in this file's header. */
export const SERVICE_INTERFACE = "android.view.InputMethod";
/** The other constant from the same dump: `<meta-data android:name>` → `res/xml/method.xml`. */
export const SERVICE_META_DATA = "android.view.im";

/**
 * The `<service>` block whose `android:name` ends with `serviceName`, or `null` when there is
 * no such service.
 *
 * Sliced by element, not by searching the whole document: this fragment holds six components
 * and several intent filters, so a whole-document search would let a sibling's `<action>`
 * answer for the IME. `null` (no such service) is kept distinct from `""` (a service with no
 * action) so R0 can tell "we could not find it" from "it is empty".
 */
export function serviceBlock(xml, serviceName) {
  const open = /<service\b[^>]*android:name="([^"]+)"/g;
  let m;
  while ((m = open.exec(xml)) !== null) {
    if (!m[1].endsWith(serviceName)) continue;
    const end = xml.indexOf("</service>", m.index);
    return xml.slice(m.index, end < 0 ? xml.length : end);
  }
  return null;
}

/** The first `<action android:name="…">` inside one block (`""` when the block has none). */
export function blockAction(block) {
  const m = block.match(/<action\b[^>]*android:name="([^"]+)"/);
  return m ? m[1] : "";
}

/** The first `<meta-data android:name="…">` inside one block (`""` when the block has none). */
export function blockMetaName(block) {
  const m = block.match(/<meta-data\b[^>]*android:name="([^"]+)"/);
  return m ? m[1] : "";
}

/** The IME service's `<action>`, or `null` when the fragment has no such service. */
export function serviceAction(xml, serviceName) {
  const block = serviceBlock(xml, serviceName);
  return block === null ? null : blockAction(block);
}

/**
 * Whether `android-component-scan.mjs`'s `PLATFORM_ACTIONS` table carries `action` as a key.
 * `null` when the table itself cannot be found (a moved file is "cannot check", not "wrong").
 */
export function tableHasAction(text, action) {
  const at = text.indexOf("export const PLATFORM_ACTIONS");
  if (at < 0) return null;
  const end = text.indexOf("\n};", at);
  return text.slice(at, end < 0 ? text.length : end).includes(`"${action}":`);
}

/** The findings for one pair of manifests. Pure, so the selftest can drive it. */
export function scan({
  fragmentXml,
  generatedXml,
  constant = SERVICE_INTERFACE,
  metaConstant = SERVICE_META_DATA,
  tableText = null,
}) {
  const findings = [];
  if (!constant) findings.push("R0 the pinned SERVICE_INTERFACE is empty");
  if (!metaConstant) findings.push("R0 the pinned SERVICE_META_DATA is empty");
  if (fragmentXml === null) {
    findings.push(`R0 no ${FRAGMENT} to read`);
    return findings;
  }
  const block = serviceBlock(fragmentXml, IME_SERVICE);
  if (block === null) {
    findings.push(`R0 ${FRAGMENT} declares no <service> named ${IME_SERVICE}`);
    return findings;
  }
  const fragmentAction = blockAction(block);
  if (!fragmentAction) {
    findings.push(`R0 the ${IME_SERVICE} <service> declares no <action>`);
  } else if (fragmentAction !== constant) {
    findings.push(
      `R1 ${FRAGMENT}: ${IME_SERVICE} advertises "${fragmentAction}", but the platform ` +
        `queries "${constant}" (${PLATFORM_CLASS}.SERVICE_INTERFACE) — the IME will install, ` +
        `resolve, and never appear in the keyboard list`,
    );
  }
  if (generatedXml != null) {
    const generatedAction = serviceAction(generatedXml, IME_SERVICE);
    if (generatedAction === null) {
      findings.push(`R2 ${GENERATED} declares no <service> named ${IME_SERVICE}`);
    } else if (generatedAction !== constant) {
      findings.push(
        `R2 ${GENERATED}: ${IME_SERVICE} advertises "${generatedAction}" — the hand-merge ` +
          `drifted from the platform constant ${constant}`,
      );
    }
  }
  const meta = blockMetaName(block);
  if (!meta) {
    findings.push(
      `R4 the ${IME_SERVICE} <service> declares no <meta-data android:name> — the platform ` +
        `would not find res/xml/method.xml, so the keyboard offers no languages`,
    );
  } else if (meta !== metaConstant) {
    findings.push(
      `R4 ${FRAGMENT}: ${IME_SERVICE} declares <meta-data android:name="${meta}">, but ` +
        `${PLATFORM_CLASS}.SERVICE_META_DATA is "${metaConstant}" — that key is what points ` +
        `the platform at res/xml/method.xml`,
    );
  }
  if (tableText != null) {
    const has = tableHasAction(tableText, constant);
    if (has === null) {
      findings.push(`R5 ${SCAN} has no PLATFORM_ACTIONS table to read`);
    } else if (!has) {
      findings.push(
        `R5 ${SCAN}'s PLATFORM_ACTIONS does not key the IME on "${constant}" — that table is ` +
          `what judges every future manifest edit, so it would redden the next round that ` +
          `spells the action correctly`,
      );
    }
  }
  return findings;
}

/** The SDK's `platforms/<version>/android.jar` jars, highest platform first. */
export function androidJars(sdk) {
  const dir = join(sdk, "platforms");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((d) => existsSync(join(dir, d, "android.jar")))
    .sort((a, b) => parseFloat(b.replace(/\D/g, "")) - parseFloat(a.replace(/\D/g, "")))
    .map((d) => join(dir, d, "android.jar"));
}

/**
 * `javap -constants` on the SDK's own class → `{ serviceInterface, serviceMetaData }`, or
 * `null` when neither can be read (no SDK, no `javap`, or an unreadable jar).
 */
export function readAuthority() {
  const sdk =
    process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT || join(homedir(), "Library/Android/sdk");
  const jars = androidJars(sdk);
  if (jars.length === 0) return null;
  for (const javap of [
    process.env.JAVA_HOME ? join(process.env.JAVA_HOME, "bin/javap") : null,
    "/usr/bin/javap",
  ].filter(Boolean)) {
    if (!existsSync(javap)) continue;
    try {
      const out = execFileSync(javap, ["-constants", "-classpath", jars[0], PLATFORM_CLASS], {
        encoding: "utf8",
      });
      const of = (field) => out.match(new RegExp(`${field}\\s*=\\s*"([^"]+)"`))?.[1];
      const serviceInterface = of("SERVICE_INTERFACE");
      if (serviceInterface) {
        return { serviceInterface, serviceMetaData: of("SERVICE_META_DATA"), jar: jars[0] };
      }
    } catch {
      // Fall through to the next candidate: an unreadable jar is "cannot check", not "mismatch".
    }
  }
  return null;
}

function read(path) {
  try {
    return readFileSync(join(ROOT, path), "utf8");
  } catch {
    return null;
  }
}

function runSelftest() {
  const cases = [];
  // The fixed pseudo-window `<service>` below is written the way the real fragment is:
  // attributes on the lines after the tag, so a same-line-only reader is caught here.
  const svc = (action, meta = SERVICE_META_DATA) =>
    `<manifest><application><service\n        android:name="com.amos.ai.glue.AmosImeService">\n` +
    `      <intent-filter>\n        <action android:name="${action}" />\n      </intent-filter>\n` +
    (meta === null ? "" : `      <meta-data\n        android:name="${meta}" />\n`) +
    `</service></application></manifest>`;
  const other = `<service android:name="com.amos.ai.glue.AlarmReceiver" android:exported="false" />`;
  // A stand-in for `android-component-scan.mjs`'s table, with the key under test swapped.
  const table = (key) => `export const PLATFORM_ACTIONS = {\n  "${key}": { who: "service" },\n};`;

  const green = () =>
    scan({ fragmentXml: svc(SERVICE_INTERFACE), generatedXml: svc(SERVICE_INTERFACE), tableText: table(SERVICE_INTERFACE) });

  cases.push(["the real spelling is green against the pinned constant", green().length === 0, green().join("; ")]);
  {
    // The shipped defect, spelled out: this is the literal that cost a device bring-up.
    const f = scan({ fragmentXml: svc("android.view.inputmethod.InputMethod"), generatedXml: null });
    cases.push([
      "the package-shaped spelling is red (R1)",
      f.some((x) => x.startsWith("R1") && x.includes("android.view.inputmethod.InputMethod")),
      f.join("; "),
    ]);
  }
  {
    const f = scan({ fragmentXml: svc(SERVICE_INTERFACE), generatedXml: svc("android.view.inputmethod.InputMethod") });
    cases.push(["a drifted generated manifest is red (R2)", f.some((x) => x.startsWith("R2")), f.join("; ")]);
  }
  {
    // R4: the second constant of the same class, and the same by-analogy trap.
    const f = scan({ fragmentXml: svc(SERVICE_INTERFACE, "android.view.inputmethod.im"), generatedXml: null });
    cases.push([
      "a package-shaped meta-data name is red (R4)",
      f.some((x) => x.startsWith("R4") && x.includes("android.view.inputmethod.im")),
      f.join("; "),
    ]);
  }
  {
    const f = scan({ fragmentXml: svc(SERVICE_INTERFACE, null), generatedXml: null });
    cases.push(["a missing meta-data is red (R4)", f.some((x) => x.startsWith("R4")), f.join("; ")]);
  }
  {
    // R5: the table that judges every future edit, taught the wrong spelling — how it shipped.
    const f = scan({
      fragmentXml: svc(SERVICE_INTERFACE),
      generatedXml: null,
      tableText: table("android.view.inputmethod.InputMethod"),
    });
    cases.push(["a table keyed on the wrong literal is red (R5)", f.some((x) => x.startsWith("R5")), f.join("; ")]);
  }
  {
    const f = scan({ fragmentXml: svc(SERVICE_INTERFACE), generatedXml: null, tableText: "// no table here" });
    cases.push(["an unreadable table is red (R5)", f.some((x) => x.startsWith("R5")), f.join("; ")]);
  }
  {
    // R0: a service whose own name we never find must not read as "correct action on nothing".
    const f = scan({ fragmentXml: other, generatedXml: null });
    cases.push(["a fragment with no IME service is red (R0)", f.some((x) => x.startsWith("R0")), f.join("; ")]);
  }
  {
    const f = scan({ fragmentXml: svc(SERVICE_INTERFACE), generatedXml: null, constant: "" });
    cases.push(["an empty pin is red (R0)", f.some((x) => x.startsWith("R0")), f.join("; ")]);
  }
  {
    // Element-scoped: the SMS receiver's filter (declared above the IME) must not answer for it.
    const twoFilters = `<application>
      <receiver android:name="com.amos.ai.glue.SmsReceiver">
        <intent-filter android:priority="999"><action android:name="android.provider.Telephony.SMS_RECEIVED" /></intent-filter>
      </receiver>${svc(SERVICE_INTERFACE)}</application>`;
    cases.push([
      "an earlier component's action does not answer for the IME",
      scan({ fragmentXml: twoFilters, generatedXml: null }).length === 0,
      scan({ fragmentXml: twoFilters, generatedXml: null }).join("; "),
    ]);
  }
  {
    const f = scan({ fragmentXml: null, generatedXml: null });
    cases.push(["an unreadable fragment is red (R0)", f.some((x) => x.startsWith("R0")), f.join("; ")]);
  }
  {
    // The repository's own three files, on disk. Fixtures pin the parser; this pins the answer.
    const f = scan({ fragmentXml: read(FRAGMENT), generatedXml: read(GENERATED), tableText: read(SCAN) });
    cases.push(["the repository's own manifests and table are clean", f.length === 0, f.join("; ")]);
  }

  let failed = 0;
  for (const [name, ok, detail] of cases) {
    if (ok) console.log(`  ok  ${name}`);
    else {
      failed += 1;
      console.error(`  FAIL ${name}${detail ? `\n       ${detail}` : ""}`);
    }
  }
  if (failed > 0) {
    console.error(`\n${failed} self-test(s) failed.`);
    process.exitCode = 1;
  } else {
    console.log(`\nAll ${cases.length} self-tests passed.`);
  }
}

function main() {
  if (process.argv.includes("--selftest")) return runSelftest();

  const fragmentXml = read(FRAGMENT);
  const generatedXml = read(GENERATED);
  const tableText = read(SCAN);
  const findings = scan({ fragmentXml, generatedXml, tableText });

  let authority = null;
  try {
    authority = readAuthority();
  } catch {
    authority = null;
  }
  if (authority === null) {
    console.log(
      `[ime-action-scan] R3 skipped: no javap + SDK android.jar resolvable on this machine, so ` +
        `the pins "${SERVICE_INTERFACE}"/"${SERVICE_META_DATA}" were not re-read off the ` +
        `platform (R1/R2/R4/R5 still ran)`,
    );
  } else {
    if (authority.serviceInterface !== SERVICE_INTERFACE) {
      findings.push(
        `R3 the pin is stale: ${PLATFORM_CLASS}.SERVICE_INTERFACE on the SDK's android.jar is ` +
          `"${authority.serviceInterface}", but this scan pins "${SERVICE_INTERFACE}"`,
      );
    }
    if (authority.serviceMetaData && authority.serviceMetaData !== SERVICE_META_DATA) {
      findings.push(
        `R3 the meta pin is stale: ${PLATFORM_CLASS}.SERVICE_META_DATA is ` +
          `"${authority.serviceMetaData}", but this scan pins "${SERVICE_META_DATA}"`,
      );
    }
  }

  if (process.argv.includes("--json")) {
    console.log(JSON.stringify({ findings, authority, pinned: { SERVICE_INTERFACE, SERVICE_META_DATA } }, null, 2));
  } else if (findings.length === 0) {
    console.log(
      `[ime-action-scan] ${IME_SERVICE} advertises "${SERVICE_INTERFACE}" with ` +
        `meta-data "${SERVICE_META_DATA}" (ok)`,
    );
  } else {
    for (const f of findings) console.error(`[ime-action-scan] ${f}`);
    console.error(`\n[ime-action-scan] FAILED — ${findings.length} finding(s).`);
    process.exitCode = 1;
  }
  return undefined;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
